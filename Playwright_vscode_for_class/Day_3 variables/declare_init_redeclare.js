var num1=123;//num declaring as 123 with var keyword

console.log("num after declaration: ",num1);

var num1=456;//redeclaring as 456 num with var keyword

console.log("num after redeclaration: ",num1);

num1=789;//reassigning as 789 num without var keyword

console.log("num after reassignment: ",num1); 

